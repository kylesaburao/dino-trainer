'use strict';
// Deterministic bookkeeping around training, so nobody has to do it by hand:
//   report  - regenerate PROGRESS.md's status block from the run's files
//   finish  - stop the trainer safely, held-out eval, export model.js, browser
//             check, report, commit (never pushes)
//   session - train, then finish: one detached command for a whole session
const fs = require('fs');
const path = require('path');
const { spawn, spawnSync } = require('child_process');
const { ROOT, readJson, pidAlive, writeAtomic } = require('./store.js');

const PROGRESS = path.join(ROOT, 'PROGRESS.md');
const BEGIN = '<!-- auto-status:begin -->';
const END = '<!-- auto-status:end -->';
const runDir = (opts) => path.resolve(opts.dir || path.join(ROOT, 'runs', 'main'));
const rel = (p) => path.relative(ROOT, p);
const tryJson = (f) => { try { return readJson(f); } catch (e) { return null; } };
const lines = (f) => { try { return fs.readFileSync(f, 'utf8').split('\n').filter(Boolean); } catch (e) { return []; } };
const mins = (ms) => `${(ms / 60000).toFixed(1)} min`;
const say = (...a) => console.log(`[${new Date().toISOString()}]`, ...a);

function liveLock(dir) {
  const lock = tryJson(path.join(dir, 'train.lock'));
  return lock && pidAlive(lock.pid) ? lock : null;
}

// ---------------------------------------------------------------------------
// report
// ---------------------------------------------------------------------------
function buildStatus(dir, extra = {}) {
  const ck = tryJson(path.join(dir, 'checkpoint.json'));
  const best = tryJson(path.join(dir, 'best.json'));
  const lock = liveLock(dir);
  let last = null, top = null;
  for (const l of lines(path.join(dir, 'metrics.jsonl'))) {
    const r = JSON.parse(l);
    last = r;
    if (!top || r.fitMax > top.fitMax) top = r;
  }
  const evals = lines(path.join(dir, 'evals.jsonl')).map(l => JSON.parse(l));
  const bestRel = rel(path.join(dir, 'best.json'));
  const held = [...evals].reverse().find(e => e.source === bestRel && best && e.generation === best.generation)
    || [...evals].reverse().find(e => e.source === bestRel) || null;
  const cfg = ck ? ck.config : best ? best.config : {};
  const target = cfg.target;
  const gen = last ? last.generation : ck ? ck.generation : 0;
  const wall = Math.max(ck ? ck.cumulativeMs || 0 : 0, last ? last.cumulativeMs || 0 : 0);
  const name = rel(dir);

  const status = lock
    ? `training in progress (${name}, generation ${gen}, PID ${lock.pid})`
    : ck ? `training stopped at generation ${ck.generation} (${ck.reason})` : 'training not started';
  const heldText = held
    ? `${held.median} / ${held.min} / ${held.max} (best from gen ${held.generation}, cap ${held.target}, evaluated ${held.time})`
    : 'not evaluated yet';
  const rows = [
    ['Run', `\`${name}\`: ${lock ? `**running**, PID ${lock.pid}` : ck ? `stopped (${ck.reason}, saved ${ck.savedAt})` : 'no checkpoint'}`],
    ['Target / metric', `${target ?? '–'}; median score over the 25 held-out seeds, episodes capped at the target`],
    ['Generation / cumulative wall time', `${gen} / ${mins(wall)}`],
    ['Best training score', top ? `${top.fitMax.toFixed(1)} (best candidate's mean capped score, gen ${top.generation})` : '–'],
    ['Best validation median', best ? `${best.validation.median} (min ${best.validation.min}, max ${best.validation.max}) at gen ${best.generation}` : '–'],
    ['Held-out median / min / max', heldText],
    ['Throughput', last ? `${last.fps.toLocaleString('en-US')} frames/s (last generation), ${ck && ck.workers ? ck.workers : '?'} workers` : '–'],
    ['Model in model.js', (() => { try { const m = require(path.join(ROOT, 'model.js')); delete require.cache[path.join(ROOT, 'model.js')]; return `${m.source}, generation ${m.generation}`; } catch (e) { return '–'; } })()],
  ];
  if (extra.browser) rows.push(['Browser AI-mode check', extra.browser]);
  const resume = `nohup node trainer/cli.js session --resume --target ${target ?? 10000} --time-budget 70 --auto-export --dir ${name} >> ${name}/session.log 2>&1 &`;
  const block = [
    BEGIN,
    `## Training status (auto-generated by \`node trainer/cli.js report\` at ${new Date().toISOString()}; do not edit by hand)`,
    '',
    '| Item | Value |',
    '|---|---|',
    ...rows.map(([k, v]) => `| ${k} | ${String(v).replace(/\|/g, '\\|')} |`),
    '',
    `Config: \`${JSON.stringify(cfg)}\``,
    '',
    `Resume (train, then eval/export/browser-check/report/commit automatically): \`${resume}\``,
    END,
  ].join('\n');
  return { status, block };
}

function writeReport(dir, extra) {
  const { status, block } = buildStatus(dir, extra);
  let text = fs.existsSync(PROGRESS) ? fs.readFileSync(PROGRESS, 'utf8') : '# PROGRESS\n\n**Status:**\n';
  text = text.replace(/^\*\*Status:.*$/m, `**Status: ${status}.**`);
  const a = text.indexOf(BEGIN), b = text.indexOf(END);
  if (a >= 0 && b > a) {
    text = text.slice(0, a) + block + text.slice(b + END.length);
  } else {
    const m = text.match(/^\*\*Status:.*$/m);
    const at = m ? m.index + m[0].length : text.length;
    text = text.slice(0, at) + '\n\n' + block + '\n' + text.slice(at);
  }
  writeAtomic(PROGRESS, text);
  return status;
}

function reportCmd({ opts }) {
  const status = writeReport(runDir(opts));
  console.log(`PROGRESS.md updated: ${status}`);
}

// ---------------------------------------------------------------------------
// finish
// ---------------------------------------------------------------------------
async function stopTrainer(dir) {
  const lock = liveLock(dir);
  if (!lock) return false;
  say(`stopping trainer PID ${lock.pid} with SIGINT`);
  process.kill(lock.pid, 'SIGINT');
  const t0 = Date.now();
  while (pidAlive(lock.pid) || fs.existsSync(path.join(dir, 'train.lock'))) {
    if (Date.now() - t0 > 120000) throw new Error(`trainer PID ${lock.pid} did not stop within 120s`);
    await new Promise(r => setTimeout(r, 200));
  }
  say('trainer stopped; checkpoint saved and lock released');
  return true;
}

async function finishCmd({ config, opts }) {
  const { evalHeldOut, exportModel } = require('./cli.js');
  const dir = runDir(opts);
  await stopTrainer(dir);
  if (!fs.existsSync(path.join(dir, 'best.json'))) throw new Error(`no ${rel(path.join(dir, 'best.json'))}: nothing to evaluate or export`);

  const ev = await evalHeldOut({ dir, which: 'best', workers: opts.workers }, config.target);
  say(`held-out eval of best (gen ${ev.generation}, cap ${ev.target}): median ${ev.median}, min ${ev.min}, max ${ev.max}`);
  const ex = exportModel({ dir, which: 'best' });
  say(`exported ${ex.data.source} (gen ${ex.data.generation}) -> ${ex.file}`);

  let browser = 'skipped (--skip-browser)', browserOk = true;
  if (!opts.skipBrowser) {
    const r = spawnSync(process.execPath, [path.join(ROOT, 'test', 'browser-check.js')], { cwd: ROOT, encoding: 'utf8', timeout: 300000 });
    const out = (r.stdout || '') + (r.stderr || '');
    const summary = (out.match(/\d+\/\d+ browser checks passed/) || ['browser check did not complete'])[0];
    browserOk = r.status === 0;
    browser = browserOk ? `${summary} (headless Chrome)` : `FAILED: ${summary}; ${out.split('\n').filter(l => l.startsWith('FAIL')).join('; ')}`;
    say(`browser check: ${browser}`);
  }
  const status = writeReport(dir, { browser });
  say(`PROGRESS.md updated: ${status}`);

  if (opts.noCommit) { say('not committing (--no-commit)'); return; }
  if (!browserOk) { say('NOT committing: the browser check failed (see above)'); process.exitCode = 1; return; }
  const paths = ['model.js', 'PROGRESS.md', ...['best.json', 'metrics.jsonl', 'metrics.csv', 'evals.jsonl']
    .map(f => rel(path.join(dir, f))).filter(f => fs.existsSync(path.join(ROOT, f)))];
  const git = (...a) => spawnSync('git', a, { cwd: ROOT, encoding: 'utf8' });
  const ignored = new Set(git('check-ignore', ...paths).stdout.split('\n').filter(Boolean));
  const toCommit = paths.filter(p => !ignored.has(p));
  git('add', '--', ...toCommit);
  if (git('diff', '--cached', '--quiet', '--', ...toCommit).status === 0) { say('nothing changed; no commit'); return; }
  const msg = `Training ${rel(dir)}: gen ${ev.generation} best, held-out median ${ev.median} (min ${ev.min}, max ${ev.max}, target ${ev.target})`;
  const c = git('commit', '-m', msg, '--', ...toCommit);
  if (c.status !== 0) throw new Error(`git commit failed: ${c.stderr || c.stdout}`);
  say(`committed: ${msg}`);
}

// ---------------------------------------------------------------------------
// session: train (with the given options), then finish
// ---------------------------------------------------------------------------
async function sessionCmd(args) {
  const FINISH_ONLY = new Set(['--no-commit', '--skip-browser']);
  const trainArgs = process.argv.slice(3).filter(a => !FINISH_ONLY.has(a));
  const child = spawn(process.execPath, [path.join(__dirname, 'cli.js'), 'train', ...trainArgs], { cwd: ROOT, stdio: 'inherit' });
  let signals = 0;
  const forward = (sig) => {
    signals++;
    if (signals > 1) { say('second signal: exiting without finishing'); process.exit(130); }
    say(`${sig}: stopping training, then finishing (send again to abort)`);
    child.kill('SIGINT');
  };
  process.on('SIGINT', () => forward('SIGINT'));
  process.on('SIGTERM', () => forward('SIGTERM'));
  const code = await new Promise(res => child.on('exit', (c, s) => res(c === null ? 128 : c)));
  if (code !== 0 && code !== 130 && code !== 143) throw new Error(`train exited with code ${code}; not finishing`);
  say(`training ended (exit ${code}); finishing`);
  await finishCmd(args);
  say('session complete');
}

module.exports = { buildStatus, writeReport, reportCmd, finishCmd, sessionCmd };
